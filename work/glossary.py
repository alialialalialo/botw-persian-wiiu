import re
Z='‌'
L=r'[\u0621-\u06d3]'
G=[
 (r'(?:اوروبوزا|اُربوسا|اربوسا|اوربوسا)','اوربوسا'),
 (r'داروكورو|داروكرو|داروكر(?!%s)'%L,'داروك'),
 (r'(?<!%s)مدو(?!%s)'%(L,L),'مدوه'),
 (r'(?<!%s)ريبال'%L,'ريوال'),
 (r'(?<!%s)شيدو[نی]?(?!%s)'%(L,L),'سيدون'),
 (r'(?:اِنوكيدا|اينوكيدا)','هادسون'),
 (r'جانوران%s?(?: )?(?:الهی|مقدس)'%Z,'هيولاهای مقدس'),
 (r'جانور مقدس|هيولای الهی','هيولای مقدس'),
 (r'(?:اوردورا|اورادورا)','دينرال'),
 (r'(?:فُرودورا|فرودورا)','فاروش'),
 (r'(?:نِردورا|نردورا|نرودورا)','نايدرا'),
 (r'(?<!ايزد)(?:بانوی|بانو|الهه) هايليا','ايزدبانو هايليا'),
 (r'گِرودو','گرودو'),
 (r'گوی(%s?ها| ها)? رستگاری'%Z,r'گوی\1 روح'),
 (r'گوی‌های رستگاری','گوی‌های روح'),
 (r'تبلت شيكا','لوح شيكا'),
 (r'محفظه(%s?ی|%s?های)? قلب'%(Z,Z),r'ظرف\1 قلب'),
 (r'حلقه(%s?ی|%s?های)? استقامت'%(Z,Z),r'جام\1 استقامت'),
 (r'زيارتگاه','معبد'),
 (r'مقبره(?=%s?ی? رستاخيز)'%Z,'معبد'),
]
GR=[(re.compile(a),b) for a,b in G]
def gl(t):
    for rx,b in GR: t=rx.sub(b,t)
    return t
